    private void cargarTabla() {
//Definicion del modelo de tabla
       
     DefaultTableModel modeloTabla = new DefaultTableModel(){
     
         //evitamos que las filas y las columnas se puedan editar desde la interfaz grafica
         @Override
         public boolean isCellEditable (int row, int column){return false;}
     };
     
     //establecemos los nombres de las columnas
     String titulos[] = {"Num", "Nombre", "Color", "Raza", "Alergico", "At.esp", "Nom dueño", "Cel.dueño"};
     modeloTabla.setColumnIdentifiers(titulos);
     
     //Carga de datos desde la BD
     List <Mascota> listaMascotas = control.traerMascotas(); 
     
     //recorrer la lista y mostrar los elementos de la lista
     if(listaMascotas != null){
     
         for(Mascota masco: listaMascotas){
         
           Object[] objeto = {masco.getNumCliente(),masco.getNombre(), masco.getColor(), masco.getAlergico(), masco.getAtencionEspecial(), 
           masco.getUnDuenio().getNombre(), masco.getUnDuenio().getCelDuenio()}; 
           
           modeloTabla.addRow(objeto);
         }   
     }

       tablaMascotas.setModel(modeloTabla);
    }
